// Generates src/components/glyphs.ts from the App's icon set (app/lib/widgets/l_icons.dart), so the
// admin draws exactly the same glyphs as the App. Run after the App's icons change:
//
//   pnpm run glyphs
//
// Reads every `static const <name> = LGlyph('<name>', [ _S(...), _F(...), _X(..., extra), _XF(...) ], proto: true)`
// and keeps the path data as is (including the `O cx cy r` circle shorthand, expanded at render time).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = path.join(root, '..', 'app', 'lib', 'widgets', 'l_icons.dart');
const out = path.join(root, 'src', 'components', 'glyphs.ts');

const dart = fs.readFileSync(src, 'utf8');

/** Text of the balanced (...) group starting at `open` (index of the opening paren), without the parens. */
function group(s, open) {
  let depth = 0;
  let quote = false;
  for (let i = open; i < s.length; i++) {
    const c = s[i];
    if (c === "'") quote = !quote;
    if (quote) continue;
    if (c === '(') depth++;
    if (c === ')' && --depth === 0) return s.slice(open + 1, i);
  }
  throw new Error('unbalanced parens at ' + open);
}

const glyphs = [];
const decl = /static const (\w+)\s*=\s*LGlyph\(/g;
let m;
while ((m = decl.exec(dart))) {
  const body = group(dart, decl.lastIndex - 1);
  const parts = [];
  const part = /\b_(S|F|X|XF)\(((?:\s*'[^']*')+)\s*(?:,\s*(-?[\d.]+))?\s*\)/g;
  let p;
  while ((p = part.exec(body))) {
    const d = [...p[2].matchAll(/'([^']*)'/g)].map((x) => x[1]).join('');
    const kind = p[1];
    const o = { d };
    if (kind === 'F' || kind === 'XF') o.fill = true;
    if (kind === 'X' || kind === 'XF') o.cut = true;
    if (p[3] && Number(p[3]) !== 0) o.extra = Number(p[3]);
    parts.push(o);
  }
  if (!parts.length) throw new Error(`no parts in ${m[1]}`);
  glyphs.push({ name: m[1], parts, proto: /proto:\s*true/.test(body) });
}

const order = /static const all = <LGlyph>\[([^\]]*)\]/.exec(dart);
if (!order) throw new Error('LIcons.all not found');
const listed = order[1].split(/[\s,/]+/).filter(Boolean);
const missing = glyphs.filter((g) => !listed.includes(g.name)).map((g) => g.name);
if (missing.length) throw new Error('not in LIcons.all: ' + missing.join(', '));

const q = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const lines = glyphs.map((g) => {
  const parts = g.parts
    .map((p) => '{ d: ' + q(p.d) + (p.fill ? ', fill: true' : '') + (p.cut ? ', cut: true' : '') + (p.extra ? `, extra: ${p.extra}` : '') + ' }')
    .join(', ');
  return `  ${g.name}: { parts: [${parts}]${g.proto ? ', proto: true' : ''} },`;
});

const text = `// Generated by scripts/gen-glyphs.cjs from app/lib/widgets/l_icons.dart. Do not edit: change the App's
// icons and run \`pnpm run glyphs\`. Admin-only glyphs live in glyphsAdmin.ts.
//
// 24×24 grid, round caps and joins. Parts are drawn in order: stroke, fill (with a thin edge stroke), or
// cut (erases what is drawn before it; \`extra\` widens a stroked cut). \`O cx cy r\` is a full circle.
// \`proto\`: taken from the prototype (docs/资料包/05_原型源文件).

export interface GlyphPart {
  d: string;
  fill?: boolean;
  cut?: boolean;
  extra?: number;
}

export interface GlyphDef {
  parts: GlyphPart[];
  proto?: boolean;
}

export const APP_GLYPHS = {
${lines.join('\n')}
} satisfies Record<string, GlyphDef>;
`;

fs.writeFileSync(out, text);
console.log(`wrote ${path.relative(root, out)}: ${glyphs.length} glyphs`);
